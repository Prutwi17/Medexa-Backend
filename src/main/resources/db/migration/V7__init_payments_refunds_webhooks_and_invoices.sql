-- Phase 6: Internal payment records, payment history events, Razorpay webhook deduplication, refunds, and PDF invoices

CREATE TABLE IF NOT EXISTS payments (
    id BIGINT NOT NULL AUTO_INCREMENT,
    payment_reference VARCHAR(64) NOT NULL,
    checkout_session_id BIGINT NOT NULL,
    customer_id BIGINT NOT NULL,
    gateway_provider VARCHAR(30) NOT NULL DEFAULT 'RAZORPAY',
    gateway_order_id VARCHAR(120) NOT NULL,
    gateway_payment_id VARCHAR(120) NULL,
    gateway_signature VARCHAR(255) NULL,
    amount DECIMAL(12, 2) NOT NULL,
    refunded_amount DECIMAL(12, 2) NOT NULL DEFAULT 0.00,
    currency VARCHAR(10) NOT NULL DEFAULT 'INR',
    status VARCHAR(30) NOT NULL DEFAULT 'CREATED',
    verification_method VARCHAR(30) NULL,
    last_gateway_status VARCHAR(50) NULL,
    failure_code VARCHAR(100) NULL,
    failure_reason VARCHAR(500) NULL,
    idempotency_key VARCHAR(100) NULL,
    authorized_at TIMESTAMP(6) NULL,
    captured_at TIMESTAMP(6) NULL,
    failed_at TIMESTAMP(6) NULL,
    created_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    updated_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT pk_payments PRIMARY KEY (id),
    CONSTRAINT uk_payments_reference UNIQUE (payment_reference),
    CONSTRAINT uk_payments_checkout UNIQUE (checkout_session_id),
    CONSTRAINT uk_payments_gateway_order UNIQUE (gateway_order_id),
    CONSTRAINT uk_payments_gateway_payment UNIQUE (gateway_payment_id),
    CONSTRAINT uk_payments_idempotency UNIQUE (idempotency_key),
    CONSTRAINT fk_payments_checkout FOREIGN KEY (checkout_session_id) REFERENCES checkout_sessions (id) ON DELETE CASCADE,
    CONSTRAINT fk_payments_customer FOREIGN KEY (customer_id) REFERENCES users (id) ON DELETE CASCADE,
    INDEX idx_payments_customer_status (customer_id, status, created_at),
    INDEX idx_payments_status_time (status, created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS payment_events (
    id BIGINT NOT NULL AUTO_INCREMENT,
    payment_id BIGINT NOT NULL,
    event_source VARCHAR(40) NOT NULL,
    event_type VARCHAR(60) NOT NULL,
    previous_status VARCHAR(30) NULL,
    new_status VARCHAR(30) NOT NULL,
    gateway_reference VARCHAR(120) NULL,
    notes VARCHAR(500) NULL,
    created_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    CONSTRAINT pk_payment_events PRIMARY KEY (id),
    CONSTRAINT fk_payment_events_payment FOREIGN KEY (payment_id) REFERENCES payments (id) ON DELETE CASCADE,
    INDEX idx_payment_events_payment_time (payment_id, created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS razorpay_webhook_events (
    id BIGINT NOT NULL AUTO_INCREMENT,
    event_id VARCHAR(150) NOT NULL,
    event_type VARCHAR(80) NOT NULL,
    razorpay_order_id VARCHAR(120) NULL,
    razorpay_payment_id VARCHAR(120) NULL,
    razorpay_refund_id VARCHAR(120) NULL,
    signature_verified BOOLEAN NOT NULL DEFAULT FALSE,
    processing_status VARCHAR(40) NOT NULL,
    processing_notes VARCHAR(500) NULL,
    raw_payload TEXT NOT NULL,
    received_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    processed_at TIMESTAMP(6) NULL,
    CONSTRAINT pk_razorpay_webhook_events PRIMARY KEY (id),
    CONSTRAINT uk_webhook_event_id UNIQUE (event_id),
    INDEX idx_webhook_order_payment (razorpay_order_id, razorpay_payment_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS refunds (
    id BIGINT NOT NULL AUTO_INCREMENT,
    refund_reference VARCHAR(64) NOT NULL,
    order_id BIGINT NOT NULL,
    payment_id BIGINT NOT NULL,
    customer_id BIGINT NOT NULL,
    amount DECIMAL(12, 2) NOT NULL,
    currency VARCHAR(10) NOT NULL DEFAULT 'INR',
    reason VARCHAR(500) NOT NULL,
    status VARCHAR(30) NOT NULL DEFAULT 'REQUESTED',
    gateway_refund_id VARCHAR(120) NULL,
    idempotency_key VARCHAR(100) NULL,
    initiated_by_user_id BIGINT NULL,
    processed_by_user_id BIGINT NULL,
    failure_reason VARCHAR(500) NULL,
    admin_notes VARCHAR(500) NULL,
    processed_at TIMESTAMP(6) NULL,
    created_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    updated_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT pk_refunds PRIMARY KEY (id),
    CONSTRAINT uk_refunds_reference UNIQUE (refund_reference),
    CONSTRAINT uk_refunds_gateway_id UNIQUE (gateway_refund_id),
    CONSTRAINT uk_refunds_idempotency UNIQUE (idempotency_key),
    CONSTRAINT fk_refunds_order FOREIGN KEY (order_id) REFERENCES orders (id) ON DELETE CASCADE,
    CONSTRAINT fk_refunds_payment FOREIGN KEY (payment_id) REFERENCES payments (id) ON DELETE CASCADE,
    CONSTRAINT fk_refunds_customer FOREIGN KEY (customer_id) REFERENCES users (id) ON DELETE CASCADE,
    INDEX idx_refunds_order (order_id),
    INDEX idx_refunds_customer_time (customer_id, created_at),
    INDEX idx_refunds_status (status, created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS invoices (
    id BIGINT NOT NULL AUTO_INCREMENT,
    invoice_number VARCHAR(64) NOT NULL,
    order_id BIGINT NOT NULL,
    customer_id BIGINT NOT NULL,
    pharmacy_id BIGINT NOT NULL,
    pharmacy_name VARCHAR(200) NOT NULL,
    pharmacy_address VARCHAR(350) NOT NULL,
    customer_name VARCHAR(150) NOT NULL,
    customer_address VARCHAR(400) NOT NULL,
    items_subtotal DECIMAL(12, 2) NOT NULL,
    discount_amount DECIMAL(12, 2) NOT NULL DEFAULT 0.00,
    delivery_fee DECIMAL(10, 2) NOT NULL DEFAULT 0.00,
    tax_amount DECIMAL(10, 2) NOT NULL DEFAULT 0.00,
    grand_total DECIMAL(12, 2) NOT NULL,
    tax_applicable BOOLEAN NOT NULL DEFAULT FALSE,
    tax_note VARCHAR(350) NULL,
    payment_reference VARCHAR(120) NULL,
    payment_status VARCHAR(40) NOT NULL,
    issued_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    created_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    CONSTRAINT pk_invoices PRIMARY KEY (id),
    CONSTRAINT uk_invoices_number UNIQUE (invoice_number),
    CONSTRAINT uk_invoices_order UNIQUE (order_id),
    CONSTRAINT fk_invoices_order FOREIGN KEY (order_id) REFERENCES orders (id) ON DELETE CASCADE,
    CONSTRAINT fk_invoices_customer FOREIGN KEY (customer_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT fk_invoices_pharmacy FOREIGN KEY (pharmacy_id) REFERENCES pharmacies (id) ON DELETE CASCADE,
    INDEX idx_invoices_customer (customer_id, issued_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
