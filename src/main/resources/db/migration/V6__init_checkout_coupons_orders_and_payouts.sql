CREATE TABLE IF NOT EXISTS checkout_sessions (
    id BIGINT NOT NULL AUTO_INCREMENT,
    checkout_reference VARCHAR(64) NOT NULL,
    customer_id BIGINT NOT NULL,
    address_id BIGINT NULL,
    delivery_recipient_name VARCHAR(150) NOT NULL,
    delivery_phone VARCHAR(30) NOT NULL,
    delivery_address_line1 VARCHAR(250) NOT NULL,
    delivery_address_line2 VARCHAR(250) NULL,
    delivery_city VARCHAR(100) NOT NULL,
    delivery_state VARCHAR(100) NOT NULL,
    delivery_postal_code VARCHAR(20) NOT NULL,
    coupon_code VARCHAR(40) NULL,
    status VARCHAR(30) NOT NULL DEFAULT 'AWAITING_PAYMENT',
    items_subtotal DECIMAL(12, 2) NOT NULL DEFAULT 0.00,
    discount_amount DECIMAL(12, 2) NOT NULL DEFAULT 0.00,
    delivery_fee_total DECIMAL(12, 2) NOT NULL DEFAULT 0.00,
    tax_amount DECIMAL(12, 2) NOT NULL DEFAULT 0.00,
    grand_total DECIMAL(12, 2) NOT NULL DEFAULT 0.00,
    currency VARCHAR(10) NOT NULL DEFAULT 'INR',
    razorpay_order_id VARCHAR(100) NULL,
    payment_reference VARCHAR(120) NULL,
    idempotency_key VARCHAR(100) NULL,
    expires_at TIMESTAMP(6) NOT NULL,
    paid_at TIMESTAMP(6) NULL,
    cancelled_at TIMESTAMP(6) NULL,
    failure_reason VARCHAR(500) NULL,
    created_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    updated_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT pk_checkout_sessions PRIMARY KEY (id),
    CONSTRAINT uk_checkout_reference UNIQUE (checkout_reference),
    CONSTRAINT uk_checkout_idempotency UNIQUE (idempotency_key),
    CONSTRAINT fk_checkout_customer FOREIGN KEY (customer_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT fk_checkout_address FOREIGN KEY (address_id) REFERENCES customer_addresses (id) ON DELETE SET NULL,
    INDEX idx_checkout_customer_status (customer_id, status, created_at),
    INDEX idx_checkout_status_expiry (status, expires_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS orders (
    id BIGINT NOT NULL AUTO_INCREMENT,
    order_number VARCHAR(64) NOT NULL,
    checkout_session_id BIGINT NOT NULL,
    customer_id BIGINT NOT NULL,
    pharmacy_id BIGINT NOT NULL,
    address_id BIGINT NULL,
    shipping_recipient_name VARCHAR(150) NOT NULL,
    shipping_phone VARCHAR(30) NOT NULL,
    shipping_address VARCHAR(500) NOT NULL,
    shipping_city VARCHAR(100) NOT NULL,
    shipping_state VARCHAR(100) NOT NULL,
    shipping_postal_code VARCHAR(20) NOT NULL,
    status VARCHAR(40) NOT NULL DEFAULT 'PAYMENT_PENDING',
    payment_status VARCHAR(30) NOT NULL DEFAULT 'PENDING',
    items_subtotal DECIMAL(12, 2) NOT NULL DEFAULT 0.00,
    discount_amount DECIMAL(12, 2) NOT NULL DEFAULT 0.00,
    delivery_fee DECIMAL(10, 2) NOT NULL DEFAULT 0.00,
    tax_amount DECIMAL(10, 2) NOT NULL DEFAULT 0.00,
    grand_total DECIMAL(12, 2) NOT NULL DEFAULT 0.00,
    platform_commission_amount DECIMAL(12, 2) NOT NULL DEFAULT 0.00,
    pharmacy_payout_amount DECIMAL(12, 2) NOT NULL DEFAULT 0.00,
    delivery_assignment_status VARCHAR(30) NOT NULL DEFAULT 'UNASSIGNED',
    delivery_eta_minutes INT NULL,
    requires_prescription BOOLEAN NOT NULL DEFAULT FALSE,
    all_prescriptions_verified BOOLEAN NOT NULL DEFAULT TRUE,
    cancellation_reason VARCHAR(500) NULL,
    cancelled_by_role VARCHAR(30) NULL,
    refund_eligible BOOLEAN NOT NULL DEFAULT FALSE,
    refund_status VARCHAR(30) NOT NULL DEFAULT 'NONE',
    refund_reason VARCHAR(500) NULL,
    placed_at TIMESTAMP(6) NULL,
    accepted_at TIMESTAMP(6) NULL,
    prepared_at TIMESTAMP(6) NULL,
    ready_at TIMESTAMP(6) NULL,
    cancelled_at TIMESTAMP(6) NULL,
    created_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    updated_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT pk_orders PRIMARY KEY (id),
    CONSTRAINT uk_orders_number UNIQUE (order_number),
    CONSTRAINT fk_orders_checkout FOREIGN KEY (checkout_session_id) REFERENCES checkout_sessions (id) ON DELETE CASCADE,
    CONSTRAINT fk_orders_customer FOREIGN KEY (customer_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT fk_orders_pharmacy FOREIGN KEY (pharmacy_id) REFERENCES pharmacies (id) ON DELETE CASCADE,
    CONSTRAINT fk_orders_address FOREIGN KEY (address_id) REFERENCES customer_addresses (id) ON DELETE SET NULL,
    INDEX idx_orders_customer_time (customer_id, created_at),
    INDEX idx_orders_pharmacy_status (pharmacy_id, status, created_at),
    INDEX idx_orders_checkout (checkout_session_id),
    INDEX idx_orders_status (status, created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS order_items (
    id BIGINT NOT NULL AUTO_INCREMENT,
    order_id BIGINT NOT NULL,
    medicine_id BIGINT NOT NULL,
    prescription_id BIGINT NULL,
    medicine_name VARCHAR(200) NOT NULL,
    medicine_slug VARCHAR(230) NOT NULL,
    brand VARCHAR(150) NOT NULL,
    pack_size VARCHAR(80) NOT NULL,
    classification_code VARCHAR(40) NOT NULL,
    prescription_required BOOLEAN NOT NULL DEFAULT FALSE,
    quantity INT NOT NULL,
    mrp_price DECIMAL(10, 2) NOT NULL,
    unit_price DECIMAL(10, 2) NOT NULL,
    line_subtotal DECIMAL(12, 2) NOT NULL,
    discount_allocated DECIMAL(10, 2) NOT NULL DEFAULT 0.00,
    tax_amount DECIMAL(10, 2) NOT NULL DEFAULT 0.00,
    batch_allocations_summary VARCHAR(1000) NULL,
    created_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    CONSTRAINT pk_order_items PRIMARY KEY (id),
    CONSTRAINT fk_order_items_order FOREIGN KEY (order_id) REFERENCES orders (id) ON DELETE CASCADE,
    CONSTRAINT fk_order_items_medicine FOREIGN KEY (medicine_id) REFERENCES medicines (id),
    CONSTRAINT fk_order_items_prescription FOREIGN KEY (prescription_id) REFERENCES prescriptions (id) ON DELETE SET NULL,
    INDEX idx_order_items_order (order_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS order_status_history (
    id BIGINT NOT NULL AUTO_INCREMENT,
    order_id BIGINT NOT NULL,
    previous_status VARCHAR(40) NULL,
    new_status VARCHAR(40) NOT NULL,
    actor_user_id BIGINT NULL,
    actor_role VARCHAR(30) NOT NULL,
    actor_name VARCHAR(150) NOT NULL,
    notes VARCHAR(500) NULL,
    created_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    CONSTRAINT pk_order_status_history PRIMARY KEY (id),
    CONSTRAINT fk_order_history_order FOREIGN KEY (order_id) REFERENCES orders (id) ON DELETE CASCADE,
    INDEX idx_order_history_time (order_id, created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
